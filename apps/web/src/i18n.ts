export type MessageKey = keyof typeof MESSAGES;
const COLUMN = { fi: 0, sv: 1, ru: 2, es: 3 } as const;

export function translate(
  locale: Locale,
  key: MessageKey,
  values: Readonly<Record<string, string | number>> = {},
): string {
  const text = locale === "en" ? key : MESSAGES[key][COLUMN[locale]];
  return text.replace(/\{(\w+)\}/g, (_match, name: string) => {
    const value = values[name];
    if (value === undefined) throw new Error("Missing translation parameter.");
    return String(value);
  });
}

export function translateError(locale: Locale, message: string): string {
  return isMessageKey(message) && !/\{\w+\}/.test(message)
    ? translate(locale, message)
    : translate(locale, "Could not generate data.");
}

function isMessageKey(message: string): message is MessageKey {
  return Object.hasOwn(MESSAGES, message);
}
