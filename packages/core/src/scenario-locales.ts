export function scenarioWord(value: string, locale: Locale): string {
  if (locale === "en") return value;
  const index = words.indexOf(value);
  if (index === -1) return value;
  const translated = translations[locale][index];
  if (translated === undefined)
    throw new TypeError("Incomplete scenario dictionary.");
  return translated;
}
